#!/usr/bin/env node
/**
 * Pushes i18n/glossary.lotm-zh.json into the shared Weblate glossary.
 *
 * Replaces build-crowdin-glossary.mjs. Crowdin took a CSV upload; Weblate models
 * a glossary as an ordinary component whose units happen to be terms, so terms
 * are created through the units API instead of a file import.
 *
 * The glossary component lives in the coi-plugin project and is SHARED with
 * mysterria-website (Component.links), so one run covers both. That sharing is
 * the whole point: 途径 and 序列 have to read the same in game as on the site.
 *
 * Only English -> Simplified Chinese is pushed. Traditional is absent on purpose
 * - it is generated by build-zh-tw.mjs from the Simplified text and is not a
 * Weblate language at all. The zh-TW column in the JSON feeds that converter's
 * override list, not Weblate.
 *
 *   WEBLATE_URL=https://weblate.mysterria.net \
 *   WEBLATE_API_TOKEN=... \
 *   node scripts/sync-glossary-weblate.mjs --dry-run
 */

import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "i18n", "glossary.lotm-zh.json");

const BASE = (process.env.WEBLATE_URL ?? "https://weblate.mysterria.net").replace(/\/$/, "");
const TOKEN = process.env.WEBLATE_API_TOKEN;
const PROJECT = "coi-plugin";
const COMPONENT = "glossary";
// Weblate normalises zh-CN to zh_Hans internally; this is the code it stores.
const LANGUAGE = "zh_Hans";

const DRY_RUN = process.argv.includes("--dry-run");

// Cloudflare fronts weblate.mysterria.net and answers an unrecognised agent with
// a 403 (error 1010) before the request reaches Weblate at all.
const HEADERS = {
    "Authorization": `Token ${TOKEN}`,
    "Content-Type": "application/json",
    "Accept": "application/json",
    "User-Agent": "mysterria-glossary-sync/1.0 (+https://mysterria.net)",
};

async function api(method, urlOrPath, body) {
    const url = urlOrPath.startsWith("http") ? urlOrPath : `${BASE}${urlOrPath}`;
    const response = await fetch(url, {
        method,
        headers: HEADERS,
        body: body === undefined ? undefined : JSON.stringify(body),
    });
    if (!response.ok) {
        throw new Error(`${method} ${url} -> ${response.status}\n${(await response.text()).slice(0, 500)}`);
    }
    return response.status === 204 ? {} : response.json();
}

/** Walks every page of a paginated list endpoint. */
async function listAll(path) {
    const out = [];
    let next = `${BASE}${path}`;
    while (next) {
        const page = await api("GET", next);
        out.push(...page.results);
        next = page.next;
    }
    return out;
}

/** English term -> {target, note}, flattened from both sections of the JSON. */
function readTerms() {
    const data = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
    const terms = new Map();

    const add = (english, target, note) => {
        if (!english || !target) return;
        // First writer wins, so a core term is never shadowed by a pathway label.
        if (!terms.has(english)) terms.set(english, {target, note: note ?? ""});
    };

    for (const entry of data.core) {
        add(entry.en, entry["zh-CN"], entry.note);
    }
    for (const [id, entry] of Object.entries(data.pathways)) {
        // The section carries a $comment key alongside the real pathway ids.
        if (id.startsWith("$") || typeof entry !== "object") continue;
        add(entry.en, entry["zh-CN"], entry.note);
        // The pathway label and its deity are different terms that happen to
        // share an entry - "Fool" is 占卜家 the route, 愚者 the god.
        if (entry["deity-zh-CN"]) {
            add(`${entry.en} (deity)`, entry["deity-zh-CN"], entry.note);
        }
    }
    return terms;
}

async function main() {
    if (!TOKEN) {
        console.error("error: WEBLATE_API_TOKEN is not set");
        process.exit(2);
    }

    const terms = readTerms();
    console.log(`${SOURCE}: ${terms.size} term(s)`);

    // The glossary starts with no Simplified Chinese translation at all, and
    // units can only be added to a translation that exists.
    const translations = await listAll(`/api/components/${PROJECT}/${COMPONENT}/translations/`);
    if (!translations.some((t) => t.language.code === LANGUAGE)) {
        console.log(`creating ${LANGUAGE} translation in the glossary`);
        if (!DRY_RUN) {
            await api("POST", `/api/components/${PROJECT}/${COMPONENT}/translations/`,
                {language_code: LANGUAGE});
        }
    }

    const unitsPath = `/api/translations/${PROJECT}/${COMPONENT}/${LANGUAGE}/units/`;
    const existing = DRY_RUN && !translations.some((t) => t.language.code === LANGUAGE)
        ? []
        : await listAll(unitsPath);
    const bySource = new Map(existing.map((unit) => [unit.source?.[0] ?? "", unit]));

    let added = 0;
    let explained = 0;
    let unchanged = 0;

    for (const [english, {target, note}] of terms) {
        let unit = bySource.get(english);

        if (!unit) {
            console.log(`  + ${english} -> ${target}`);
            if (!DRY_RUN) {
                // source/target, not key/value: TBX is a bilingual format, so a
                // unit has both sides rather than a key naming a monolingual slot.
                // Both are lists because a unit can carry plural forms; a term
                // has exactly one of each.
                unit = await api("POST", unitsPath, {source: [english], target: [target]});
            }
            added++;
        } else {
            unchanged++;
        }

        // `explanation` is a property of the SOURCE string, not of a translation,
        // so patching the zh_Hans unit is rejected with 403. Weblate hands back
        // the source unit's URL on every unit; that is what has to be written.
        // The JSON is authoritative for these notes - they are canon rules, not
        // translator commentary - so they are kept in step rather than preserved.
        if (note && unit?.source_unit && !DRY_RUN) {
            const source = await api("GET", unit.source_unit);
            if (source.explanation !== note) {
                await api("PATCH", unit.source_unit, {explanation: note});
                explained++;
            }
        }
    }

    console.log(`\n${DRY_RUN ? "[dry-run] " : ""}added ${added}, explanations written ${explained}, already present ${unchanged}`);
    console.log(`${BASE}/projects/${PROJECT}/${COMPONENT}/`);
}

main().catch((error) => {
    console.error(`\n${error.message}`);
    process.exit(1);
});
